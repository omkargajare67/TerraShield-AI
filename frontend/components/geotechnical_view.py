"""Streamlit component for Phase 3 Geotechnical Intelligence Engine."""

import json
from pathlib import Path
from typing import Any, Dict, Optional
import requests
import streamlit as st


def render_geotechnical_tab(api_base_url: str) -> None:
    """Render the Geotechnical Intelligence tab in Streamlit."""
    st.markdown("## 📐 Geotechnical Intelligence Engine")
    st.markdown(
        "Evaluate hillslope stability using limit-equilibrium **Infinite Slope Analysis** "
        "and vegetative root reinforcement modeling (**Wu-Waldron Formulation**)."
    )

    # Persistent Geotechnical Scientific Disclaimer
    st.markdown(
        """
        <div class="warning-banner">
            <strong>⚠️ Exploratory Geotechnical Model Notice:</strong><br/>
            Results generated by this engine are exploratory limit-equilibrium scenario outputs
            based on user-supplied parameter assumptions. They do <strong>NOT</strong> represent
            statistically calibrated landslide failure probabilities, empirical hazard forecasts,
            or certified engineering designs. An on-site geotechnical engineering investigation is
            required for any structural or life-safety decisions.
        </div>
        """,
        unsafe_allow_html=True,
    )

    # 1. Input Data Status Section
    st.subheader("1. Terrain Slope Input Data Status")
    status_data = None
    try:
        resp = requests.get(f"{api_base_url}/api/v1/geotechnical/status", timeout=5)
        if resp.status_code == 200:
            status_data = resp.json()
    except Exception as err:
        st.warning(f"Could not connect to geotechnical backend status endpoint: {err}")

    if status_data:
        col_s1, col_s2, col_s3 = st.columns([1.5, 1.5, 1])
        with col_s1:
            if status_data.get("real_slope_available"):
                st.success("✅ **Real Wayanad Slope GeoTIFF:** Available")
            else:
                st.error("❌ **Real Wayanad Slope GeoTIFF:** Missing")
            st.caption(f"Source file: `{Path(status_data.get('slope_file', '')).name}`")

        with col_s2:
            meta = status_data.get("slope_metadata")
            if meta:
                st.info(f"📐 Grid: **{meta.get('width')} × {meta.get('height')}** | CRS: **{meta.get('crs', 'N/A')}**")
                st.caption(f"Valid Pixels: {meta.get('valid_pixel_count'):,} | NoData: {meta.get('nodata_pixel_count'):,}")
            else:
                st.caption("Metadata unavailable.")

        with col_s3:
            existing_prods = status_data.get("geotechnical_products_available", [])
            st.metric("Geotech Products", len(existing_prods))
    else:
        st.info("Status check unavailable.")

    st.divider()

    # 2. Parameter Input Form
    st.subheader("2. Geotechnical Scenario Parameters")
    st.caption(
        "Specify soil mechanical parameters and vegetative root reinforcement properties. "
        "All parameters must be explicitly defined with documented provenance."
    )

    col_soil, col_root = st.columns(2)

    with col_soil:
        st.markdown("#### 🪵 Soil Parameters")
        c_prime = st.number_input(
            "Effective Soil Cohesion $c'$ (kPa)",
            min_value=0.0,
            max_value=200.0,
            value=5.0,
            step=0.5,
            help="Effective cohesive shear resistance of soil matrix.",
        )
        gamma = st.number_input(
            "Soil Unit Weight $\\gamma$ (kN/m³)",
            min_value=5.0,
            max_value=30.0,
            value=18.0,
            step=0.5,
            help="Total soil unit weight. Standard hillslope range: 16–20 kN/m³.",
        )
        z_depth = st.number_input(
            "Failure Plane Depth $z$ (m)",
            min_value=0.2,
            max_value=15.0,
            value=1.5,
            step=0.1,
            help="Vertical depth to the assumed planar translational slip surface.",
        )
        phi_prime = st.number_input(
            "Effective Friction Angle $\\phi'$ (°)",
            min_value=5.0,
            max_value=55.0,
            value=28.0,
            step=1.0,
            help="Effective angle of internal shearing resistance.",
        )
        u_pore = st.number_input(
            "Pore-Water Pressure $u$ (kPa)",
            min_value=0.0,
            max_value=100.0,
            value=0.0,
            step=1.0,
            help="Pore-water pressure acting along failure plane. 0 kPa = dry / fully drained.",
        )
        pore_assumption = st.text_input(
            "Pore-Water Assumption Description",
            value="Hydrostatic / drained baseline condition (exploratory scenario)",
        )
        soil_provenance_type = st.selectbox(
            "Soil Parameter Provenance",
            [
                "user_scenario",
                "published_reference",
                "field_measurement",
                "laboratory_measurement",
                "synthetic_fixture",
            ],
            index=0,
            help="Documented source category for the soil parameter inputs.",
        )
        soil_citation = st.text_input(
            "Soil Data Citation / Reference",
            value="Wayanad Western Ghats literature reference / illustrative scenario",
        )

    with col_root:
        st.markdown("#### 🌿 Root Reinforcement Parameters")
        col_tr_val, col_tr_unit = st.columns([2, 1])
        with col_tr_val:
            tr_input = st.number_input(
                "Root Tensile Strength $T_r$",
                min_value=1.0,
                max_value=500000.0,
                value=15.0,
                step=1.0,
                help="Mean tensile stress of root fibers.",
            )
        with col_tr_unit:
            tr_unit = st.selectbox("Unit", ["MPa", "kPa"], index=0)

        tr_kpa_display = tr_input * 1000.0 if tr_unit == "MPa" else tr_input
        st.caption(f"Normalized internal stress: **{tr_kpa_display:,.0f} kPa** (1 MPa = 1,000 kPa)")

        rar = st.number_input(
            "Root Area Ratio (RAR) [fraction]",
            min_value=0.0,
            max_value=0.1,
            value=0.0015,
            step=0.0005,
            format="%.4f",
            help="Dimensionless ratio of root cross-sectional area to soil shear plane area (typically 0.0005–0.02).",
        )
        k_factor = st.number_input(
            "Reinforcement Factor $K$",
            min_value=0.1,
            max_value=3.0,
            value=1.2,
            step=0.05,
            help="Wu-Waldron orientation factor (default 1.2 per Wu et al. 1979 / Waldron 1977).",
        )
        species_label = st.text_input(
            "Species / Root Morphology Profile",
            value="Mixed native riparian & deep-rooting shrub profile",
        )
        root_provenance_type = st.selectbox(
            "Root Parameter Provenance",
            [
                "user_scenario",
                "published_reference",
                "field_measurement",
                "laboratory_measurement",
                "synthetic_fixture",
            ],
            index=0,
        )
        root_citation = st.text_input(
            "Root Data Citation / Reference",
            value="Published Western Ghats root biomechanics literature / test scenario",
        )

    st.divider()

    # 3. Target Benchmark & Optional Calibration
    col_tgt, col_cal = st.columns(2)

    with col_tgt:
        st.markdown("#### 🎯 Target Factor of Safety")
        fs_target = st.number_input(
            "Target Factor of Safety ($FS_{target}$)",
            min_value=1.0,
            max_value=3.0,
            value=1.3,
            step=0.05,
            help="Target benchmark stability ratio. 1.3 is the exploratory project benchmark.",
        )
        st.caption(
            "ℹ️ **Note:** $FS = 1.3$ is the project demonstration benchmark, "
            "not a universal statutory engineering acceptance criterion."
        )

    with col_cal:
        st.markdown("#### 🌳 Optional Tree-Density Calibration")
        enable_density = st.checkbox(
            "Enable Empirical Stem Density Calibration",
            value=True,
            help="Only enable when empirical field data relating stem density to Root Area Ratio (RAR) is available.",
        )
        if enable_density:
            ref_stems = st.number_input("Reference Stems / Hectare", min_value=10.0, value=1200.0, step=50.0)
            ref_rar = st.number_input("Measured RAR at Reference Density", min_value=0.0001, max_value=0.1, value=0.002, format="%.4f")
            max_stems = st.number_input("Max Planting Capacity (Stems/ha)", min_value=100.0, value=2500.0, step=100.0)
            cal_note = st.text_input("Calibration Source Note", value="Empirical stand density calibration scenario")
        else:
            ref_stems, ref_rar, max_stems, cal_note = None, None, None, None
            st.caption("Stem density estimation disabled (RAR will be reported without stems/ha).")

    st.divider()

    # Build Soil and Root Payloads
    soil_payload = {
        "c_prime_kpa": c_prime,
        "gamma_kn_m3": gamma,
        "z_m": z_depth,
        "phi_prime_deg": phi_prime,
        "u_kpa": u_pore,
        "pore_water_assumption": pore_assumption,
        "provenance": {
            "c_prime": {
                "parameter_name": "c_prime_kpa",
                "value": c_prime,
                "unit": "kPa",
                "source_type": soil_provenance_type,
                "citation": soil_citation,
            },
            "phi_prime": {
                "parameter_name": "phi_prime_deg",
                "value": phi_prime,
                "unit": "deg",
                "source_type": soil_provenance_type,
                "citation": soil_citation,
            },
        },
    }

    root_payload = {
        "tensile_stress_input": tr_input,
        "tensile_stress_unit": tr_unit,
        "root_area_ratio": rar,
        "k_factor": k_factor,
        "species_label": species_label,
        "provenance": {
            "tr": {
                "parameter_name": "tensile_stress",
                "value": tr_input,
                "unit": tr_unit,
                "source_type": root_provenance_type,
                "citation": root_citation,
            }
        },
    }

    cal_payload = (
        {
            "reference_stems_per_ha": ref_stems,
            "rar_at_reference_density": ref_rar,
            "max_stems_per_ha": max_stems,
            "provenance_note": cal_note,
        }
        if enable_density
        else None
    )

    # 4. Action Buttons
    st.subheader("3. Execution & Analytical Solvers")
    col_act1, col_act2, col_act3 = st.columns(3)

    with col_act1:
        run_point_calc = st.button("🔍 Single-Point Slope Analysis", use_container_width=True)

    with col_act2:
        run_sensitivity_calc = st.button("📈 Run Sensitivity Sweep", use_container_width=True)

    with col_act3:
        run_raster_calc = st.button("🚀 Process Real Wayanad Raster", type="primary", use_container_width=True)

    # A. Single Point Analysis Execution
    if run_point_calc:
        st.markdown("### 🔍 Single-Point Analysis Results")
        sample_beta = st.slider("Test Hillslope Angle β (°)", min_value=1.0, max_value=60.0, value=32.0, step=1.0)
        req_body = {
            "beta_deg": sample_beta,
            "soil": soil_payload,
            "root": root_payload,
            "fs_target": fs_target,
            "calibration": cal_payload,
        }
        try:
            with st.spinner("Calculating stability metrics..."):
                r = requests.post(f"{api_base_url}/api/v1/geotechnical/analysis", json=req_body, timeout=10)
            if r.status_code == 200:
                pt_data = r.json()
                base_fs = pt_data.get("baseline", {}).get("factor_of_safety")
                reinf_fs = pt_data.get("reinforced", {}).get("fs_reinforced")
                delta_fs = pt_data.get("reinforced", {}).get("delta_fs")
                delta_c = pt_data.get("root_reinforcement", {}).get("delta_c_kpa")
                req_c = pt_data.get("target_solver", {}).get("delta_c_required_kpa")

                c1, c2, c3, c4 = st.columns(4)
                c1.metric("Baseline FS₀", f"{base_fs:.3f}" if base_fs else "N/A")
                c2.metric("Root-Reinforced FS", f"{reinf_fs:.3f}" if reinf_fs else "N/A", delta=f"+{delta_fs:.3f}" if delta_fs else None)
                c3.metric("Added Cohesion ΔC", f"{delta_c:.2f} kPa" if delta_c else "0.0 kPa")
                c4.metric("Cohesion Needed for FS 1.3", f"{req_c:.2f} kPa" if req_c is not None else "0.0 kPa")

                st.info(f"**Scenario Outcome:** {pt_data.get('status_label')}")
                if pt_data.get("tree_density"):
                    td = pt_data.get("tree_density")
                    st.write(f"🌱 **Estimated Stem Density:** `{td.get('stems_per_ha_required')} stems/ha` (Status: {td.get('status_label')})")
            else:
                st.error(f"Error: {r.text}")
        except Exception as err:
            st.error(f"Request failed: {err}")

    # B. Sensitivity Sweep Execution
    if run_sensitivity_calc:
        st.markdown("### 📈 Parameter Sensitivity Analysis")
        req_body = {
            "beta_deg": 30.0,
            "soil": soil_payload,
            "root": root_payload,
            "fs_target": fs_target,
        }
        try:
            with st.spinner("Computing deterministic sensitivity variations..."):
                r = requests.post(f"{api_base_url}/api/v1/geotechnical/sensitivity", json=req_body, timeout=15)
            if r.status_code == 200:
                sens_data = r.json()
                st.caption(sens_data.get("methodology_note"))
                series = sens_data.get("series", {})
                for p_key, p_info in series.items():
                    with st.expander(f"Sensitivity: {p_info.get('parameter_label')} ({p_info.get('unit')})", expanded=False):
                        pts = p_info.get("points", [])
                        table_rows = []
                        for pt in pts:
                            table_rows.append({
                                "Value": pt.get("parameter_value"),
                                "Unit": pt.get("parameter_unit"),
                                "Baseline FS": pt.get("fs_baseline"),
                                "Reinforced FS": pt.get("fs_reinforced"),
                                "Target Reached (≥1.3)": "✅ Yes" if pt.get("target_reached") else "❌ No",
                            })
                        st.table(table_rows)
            else:
                st.error(f"Sensitivity sweep error: {r.text}")
        except Exception as err:
            st.error(f"Failed to run sensitivity sweep: {err}")

    # C. Real Raster Analysis Execution
    if run_raster_calc:
        st.markdown("### 🚀 Spatial Wayanad Raster Analysis Results")
        raster_req = {
            "soil": soil_payload,
            "root": root_payload,
            "fs_target": fs_target,
            "calibration": cal_payload,
        }
        try:
            with st.spinner("Executing geotechnical raster processing on real Wayanad slope GeoTIFF..."):
                r = requests.post(f"{api_base_url}/api/v1/geotechnical/raster-analysis", json=raster_req, timeout=30)
            if r.status_code == 200:
                data = r.json()
                st.session_state["geotech_raster_results"] = data
                st.success("Raster analysis completed successfully!")
            else:
                st.error(f"Raster analysis failed ({r.status_code}): {r.text}")
        except Exception as err:
            st.error(f"Raster request error: {err}")

    # Render persisted raster analysis results if present
    raster_res = st.session_state.get("geotech_raster_results")
    if raster_res:
        st.markdown("### 🗺️ Wayanad Geotechnical Scenario Stability Analysis")
        st.warning(
            "⚠️ **Illustrative Scenario Notice:** Geotechnical outputs below were computed across the genuine "
            "Wayanad slope raster (`wayanad_slope.tif`, CRS: EPSG:4326 WGS 84) using user-supplied exploratory scenario "
            "parameters. They do NOT represent measured Wayanad soil observations or calibrated bioengineering designs."
        )

        stats = raster_res.get("statistics", {})
        base_s = stats.get("baseline_fs", {})
        reinf_s = stats.get("reinforced_fs", {})
        req_c_s = stats.get("required_cohesion_kpa", {})
        dens_s = stats.get("tree_density")
        slope_s = stats.get("slope_degrees", {})

        m1, m2, m3, m4 = st.columns(4)
        m1.metric("Mean Baseline FS", f"{base_s.get('mean', 0.0):.2f}", help=f"Range: {base_s.get('min')} to {base_s.get('max')}")
        m2.metric("Mean Reinforced FS", f"{reinf_s.get('mean', 0.0):.2f}", delta=f"{reinf_s.get('percentage_reaching_target', 0.0):.1f}% Reaching 1.3")
        m3.metric("Mean Cohesion Needed", f"{req_c_s.get('mean', 0.0):.2f} kPa", help=f"{req_c_s.get('pixels_needing_reinforcement', 0):,} pixels need reinforcement")
        if dens_s:
            m4.metric("Mean Calibrated Density", f"{dens_s.get('mean_stems_per_ha', 0.0):.0f} stems/ha", help="Linear calibrated estimate")
        else:
            m4.metric("Stem Density", "Uncalibrated", help="Calibration not enabled")

        slope_mean_str = f"{slope_s.get('mean', 9.49):.2f}°" if slope_s else "9.49°"
        slope_max_str = f"{slope_s.get('max', 58.07):.2f}°" if slope_s else "58.07°"
        st.caption(
            f"**Terrain Input:** `wayanad_slope.tif` (CRS: {raster_res.get('crs', 'EPSG:4326')}) | "
            f"Slope Mean: **{slope_mean_str}** | Slope Max: **{slope_max_str}** | "
            f"Evaluated on **{raster_res.get('calculated_slope_pixels'):,} slope pixels** "
            f"({raster_res.get('flat_terrain_pixels'):,} flat pixels < 0.1° marked undefined)."
        )

        # Multi-panel Preview
        preview_art = raster_res.get("artifacts", {}).get("preview_image")
        if preview_art:
            st.image(
                f"{api_base_url}/api/v1/geospatial/artifacts/{preview_art}",
                caption="TerraShield AI — Wayanad Geotechnical Stability Scenario Maps (4-Panel Summary)",
                use_container_width=True,
            )

        # Download Section
        st.subheader("📥 Export Geotechnical Products")
        art_rasters = raster_res.get("artifacts", {}).get("rasters", {})
        col_d1, col_d2, col_d3 = st.columns(3)

        with col_d1:
            if "fs_baseline" in art_rasters:
                st.link_button(
                    "💾 Download Baseline FS GeoTIFF",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{art_rasters['fs_baseline']}",
                    use_container_width=True,
                )
            if "fs_reinforced" in art_rasters:
                st.link_button(
                    "💾 Download Reinforced FS GeoTIFF",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{art_rasters['fs_reinforced']}",
                    use_container_width=True,
                )

        with col_d2:
            if "required_cohesion" in art_rasters:
                st.link_button(
                    "💾 Download Required ΔC GeoTIFF",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{art_rasters['required_cohesion']}",
                    use_container_width=True,
                )
            if "required_rar" in art_rasters:
                st.link_button(
                    "💾 Download Required RAR GeoTIFF",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{art_rasters['required_rar']}",
                    use_container_width=True,
                )

        with col_d3:
            summary_art = raster_res.get("artifacts", {}).get("summary_json")
            if summary_art:
                st.link_button(
                    "📄 Download Summary JSON Report",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{summary_art}",
                    use_container_width=True,
                )
            if "required_tree_density" in art_rasters:
                st.link_button(
                    "💾 Download Density GeoTIFF",
                    f"{api_base_url}/api/v1/geospatial/artifacts/{art_rasters['required_tree_density']}",
                    use_container_width=True,
                )

        # Assumptions & Provenance Details
        with st.expander("📋 View Documented Scenario Assumptions & Provenance", expanded=False):
            st.json(raster_res.get("scenario_assumptions", {}))
            st.markdown("#### Scientific Warnings & Model Boundaries:")
            for w in raster_res.get("warnings", []):
                st.markdown(f"- ⚠️ {w}")
